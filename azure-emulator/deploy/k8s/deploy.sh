#!/usr/bin/env bash
# Deploy the hosted CloudTyke sandbox (emulator + dashboard) to k3s1.
#
#   deploy/k8s/deploy.sh            build + push images, ensure secrets, apply, wait
#   SKIP_BUILD=1 IMAGE_TAG=<sha> deploy/k8s/deploy.sh   apply existing images
#
# Needs: KUBECONFIG for k3s1, docker buildx logged in to Docker Hub (bwalia).
# First run creates the secrets with fresh credentials: a seed (the default
# tenant, subscriptions and identities, but new client secrets and password),
# an admin token for /_cloudtyke/*, and the dashboard password. They are
# written once to reports/.cloudtyke-dev-credentials (git-ignored), never
# printed in CI logs, and kept on re-deploys.
set -euo pipefail
EMU=$(cd "$(dirname "$0")/../.." && pwd)
ROOT=$(cd "$EMU/.." && pwd)
NS=cloudtyke
IMAGE_TAG=${IMAGE_TAG:-$(git -C "$ROOT" rev-parse --short=12 HEAD)}
PLATFORMS=${PLATFORMS:-linux/amd64} # k3s1 nodes are amd64
BUILDER=${BUILDER:-cloudtyke}
export IMAGE_TAG

if [ -z "${SKIP_BUILD:-}" ]; then
  echo "==> building and pushing images :$IMAGE_TAG ($PLATFORMS)"
  docker buildx inspect "$BUILDER" >/dev/null 2>&1 || docker buildx create --name "$BUILDER" --driver docker-container >/dev/null
  docker buildx build --builder "$BUILDER" --platform "$PLATFORMS" --push -q \
    --build-arg VERSION="hosted-$IMAGE_TAG" --build-arg COMMIT="$IMAGE_TAG" --build-arg DATE="$(date -u +%FT%TZ)" \
    -t "bwalia/cloudtyke-emulator:$IMAGE_TAG" "$EMU" >/dev/null
  docker buildx build --builder "$BUILDER" --platform "$PLATFORMS" --push -q -t "bwalia/cloudtyke-dashboard:$IMAGE_TAG" "$ROOT/dashboard" >/dev/null
fi

kubectl create namespace "$NS" --dry-run=client -o yaml | kubectl apply -f - >/dev/null

if ! kubectl -n "$NS" get secret cloudtyke-admin >/dev/null 2>&1; then
  echo "==> first deploy: generating credentials"
  rnd() { openssl rand -base64 36 | tr -d '/+=' | cut -c1-"${1:-32}"; }
  boot=$(rnd 40) reader=$(rnd 40) ada="Ct-$(rnd 16)-1!" admin=$(rnd 48) dash=$(rnd 24)
  seed=$(sed -e "s/cloudtyke-bootstrap-secret/$boot/" -e "s/cloudtyke-reader-secret/$reader/" \
    -e "s/\"CloudTyke-Dev-1!\"/\"$ada\"/" -e "s/cloudtyke\.local/cloudtyke.dev/g" \
    -e "s/^# These credentials are LOCAL DEVELOPMENT SECRETS.*/# Hosted sandbox seed: generated by deploy\/k8s\/deploy.sh. Secret./" \
    "$EMU/internal/seed/default.yaml")
  kubectl -n "$NS" create secret generic cloudtyke-seed --from-literal=seed.yaml="$seed" >/dev/null
  kubectl -n "$NS" create secret generic cloudtyke-admin --from-literal=token="$admin" \
    --from-literal=bootstrap-secret="$boot" --from-literal=reader-secret="$reader" >/dev/null
  kubectl -n "$NS" create secret generic cloudtyke-dashboard --from-literal=password="$dash" >/dev/null
  mkdir -p "$EMU/reports"
  (umask 077; cat > "$EMU/reports/.cloudtyke-dev-credentials" <<CRED
# Hosted CloudTyke on cloudtyke.dev, created $(date -u +%FT%TZ). Keep private.
# Also in the cluster: kubectl -n $NS get secret cloudtyke-admin -o yaml
portal_url=https://portal.cloudtyke.dev
portal_user=cloudtyke
portal_password=$dash
admin_token=$admin              # X-CloudTyke-Admin-Token for /_cloudtyke/*
tenant_id=7c10d7e4-0000-4000-8000-000000000001
bootstrap_client_id=a99c0000-0000-4000-8000-000000000001
bootstrap_client_secret=$boot   # Owner at / : treat like a root credential
reader_client_id=a99c0000-0000-4000-8000-000000000002
reader_client_secret=$reader
ada_upn=ada@cloudtyke.dev
ada_password=$ada
CRED
  )
  echo "    saved to reports/.cloudtyke-dev-credentials"
fi

# Workload identity for pods in this cluster: the emulator can't discover the
# cluster's service-account issuer, so give it the issuer's public keys.
iss=$(kubectl get --raw /.well-known/openid-configuration | jq -r .issuer)
kubectl get --raw /openid/v1/jwks | jq --arg iss "$iss" '{($iss): .}' >"${TMPDIR:-/tmp}/cloudtyke-issuers.json"
kubectl -n "$NS" create configmap cloudtyke-issuers --from-file=issuers.json="${TMPDIR:-/tmp}/cloudtyke-issuers.json" \
  --dry-run=client -o yaml | kubectl apply -f - >/dev/null

echo "==> applying manifests"
envsubst '${IMAGE_TAG}' <"$EMU/deploy/k8s/cloudtyke.yaml" | kubectl apply -f - >/dev/null
kubectl -n "$NS" rollout status deploy/emulator --timeout=300s
kubectl -n "$NS" rollout status deploy/dashboard --timeout=300s
echo "==> deployed :$IMAGE_TAG"
kubectl -n "$NS" get pods -o wide
