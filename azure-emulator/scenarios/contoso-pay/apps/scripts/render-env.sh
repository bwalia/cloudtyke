#!/usr/bin/env bash
# Runs inside the CloudTyke toolbox, in the scenario's Terraform directory.
# Prints the .env the demo apps start with:
#   - resource names and the local-dev service principal (Terraform outputs)
#   - the PostgreSQL password and Cosmos DB key, read back from the payments
#     Key Vault as that service principal, for the containers that stand in for
#     those managed services. The apps themselves read them from Key Vault.
set -euo pipefail
BIN=${BIN:-tofu}
D=${CLOUDTYKE_DOMAIN:-cloudtyke.local}
out=$("$BIN" output -json)
apps=$(jq -c '.apps.value' <<<"$out")
dev=$(jq -c '.local_dev.value' <<<"$out")
a() { jq -r ".$1" <<<"$apps"; }
d() { jq -r ".$1" <<<"$dev"; }

tok=$(curl -fsS -X POST "https://login.$D/$(d tenant_id)/oauth2/v2.0/token" \
  -d grant_type=client_credentials -d client_id="$(d client_id)" \
  --data-urlencode client_secret="$(d client_secret)" -d scope="https://vault.$D/.default" | jq -r .access_token)
secret() { curl -fsS -H "Authorization: Bearer $tok" "$(a payments_vault)secrets/$1?api-version=7.5" | jq -r .value; }

# A role assignment can take a moment to apply; retry the first read.
for i in $(seq 1 20); do pg=$(secret postgres-admin-password 2>/dev/null) && break; sleep 2; done
mongo=$(secret cosmos-mongo-connection)
cosmos_key=$(python3 -c 'import sys, urllib.parse; print(urllib.parse.unquote(sys.argv[1].split("://",1)[1].split("@",1)[0].split(":",1)[1]))' "$mongo")

cat <<EOF
# Generated by scripts/up.sh from the Terraform outputs and Key Vault. Do not commit.
CLOUDTYKE_DOMAIN=$D
AZURE_TENANT_ID=$(d tenant_id)
AZURE_CLIENT_ID=$(d client_id)
AZURE_CLIENT_SECRET=$(d client_secret)
PAYMENTS_VAULT_URI=$(a payments_vault)
MERCHANT_VAULT_URI=$(a merchant_vault)
RECEIPTS_ACCOUNT=$(a receipts_account)
SETTLEMENT_ACCOUNT=$(a settle_account)
KYC_ACCOUNT=$(a kyc_account)
POSTGRES_FQDN=$(a postgres_fqdn)
COSMOS_ACCOUNT=$(a cosmos_account)
PG_PASSWORD=$pg
COSMOS_KEY=$cosmos_key
EOF
